package com.repair.data

/**
 * 每个节气「该吃什么」的真正答案 —— 不是罗列当令食材，而是按功效排序。
 *
 * 判断依据只有一条：这一节身体最容易出什么问题，所以该吃什么性味的东西。
 * 不写民俗吃食（青团、腊八粥那类），那是「这一节吃什么好吃」，不是「该补什么」。
 *
 * tier 三级：
 *   1 = 这一节最该吃（与本节主攻方向正对）
 *   2 = 也该吃（当令、平和，日常搭着吃）
 *   3 = 少量或只作调味（性味与本节不合，点到为止，或者就是不宜多吃）
 *
 * 说明：功效属中医食养通行表述（性味、归经、功效），不是现代营养学的临床结论。
 * 凡是「忌」「慎」这类涉及他人的判断，一律写清条件，不写绝对话。
 */

/**
 * 一味推荐。
 * @param name 食材名，必须与 TermData 里的 Food.name 一模一样，否则界面挂不上
 * @param tier 1 = 这一节最该吃，2 = 也该吃，3 = 少量或只作调味
 * @param why  这一节吃它起什么作用；后面半句跟慎食的条件
 */
data class Pick(val name: String, val tier: Int, val why: String)

