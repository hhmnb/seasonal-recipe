) {
    /** 「｜」前的人群，用于加粗显示 */
    val fitHead: String get() = fit.substringBefore("｜").trim()

    /** 「｜」后的做法建议 */
    val fitBody: String get() = fit.substringAfter("｜", "").trim()

    val avoidHead: String get() = avoid.substringBefore("｜").trim()

    val avoidBody: String get() = avoid.substringAfter("｜", "").trim()
}

