/** 取一道菜的宜忌说明；万一漏配，退回按标签拼的保底文案，界面不会空着 */
val RecipeRef.health: RecipeHealth
    get() = RECIPE_HEALTH["${term.name}|${recipe.name}"] ?: fallbackHealth(recipe)

private val FRIENDLY_TAGS = listOf("低钠", "高钾", "低GI", "控糖", "高纤维", "少油")

private fun fallbackHealth(r: Recipe): RecipeHealth {
    val good = r.tags.filter { FRIENDLY_TAGS.contains(it) }
    return RecipeHealth(
        why = "按「${r.sub}」的做法，应季而食。",
        fit = (if (good.isEmpty()) "一般人群" else good.joinToString("、")) + "｜按节气常规食用即可",
        avoid = "特殊体质与慢病人群｜按医嘱调整盐、油、糖的用量"
    )
}
