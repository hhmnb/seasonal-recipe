 * 普通人看不懂，也看不出自己家的情况该不该做这道菜。
 * 这里改成三句话说人话：
 *
 *   why   —— 这个节气为什么吃它（应季理由 + 食养功效）
 *   fit   —— 谁吃了有好处。格式「人群｜怎么吃」，界面把「｜」前加粗
 *   avoid —— 谁要少吃、怎么改。同样「人群｜怎么处理」
 *
 * 键为「节气名|菜名」，比按下标取稳：以后在 TermData 里插一道菜，
 * 这里的对应关系也不会整片错位。
