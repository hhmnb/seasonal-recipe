/** 节气总纲，取不到时退回气候描述，界面不会出现空白 */
val Term.gist: String
    get() = TERM_GIST[name] ?: climate

/** 原则小标题，缺失时补空串，界面自行判断是否显示 */
val Term.principleTitles: List<String>
    get() = TERM_PTITLES[name] ?: List(principle.size) { "" }

/**
 * 把内部标签翻成「厨房里的话」。
 * 界面上一律走这个函数，不直接显示「低钠 / 低GI」这类术语。
 */
fun plainTag(tag: String): String = when (tag) {
    "低钠" -> "盐少"
    "高钾" -> "钾高"
    "低GI" -> "升糖慢"
    "控糖" -> "不加糖"
    "高纤维" -> "纤维多"
    "少油" -> "油少"
    "高嘌呤" -> "嘌呤高"
    "高糖" -> "糖分高"
    "高盐" -> "很咸"
    else -> tag
}

